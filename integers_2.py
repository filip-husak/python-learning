### Automatic results of adding an integer and a float
my_int = 56
my_float = 5.4

sum_int_and_float = my_int + my_float

print(sum_int_and_float) # 61.4
print(type(sum_int_and_float)) # <class 'float'>

### If you mix integers and floats, Python will return a float as the result.

### Floor Division
my_int = 56
my_float = 5.4

floor_division_result = my_int // my_float
print(floor_division_result) # 10.0

### CZ - Floor division = celočíselné dělení, které vrací celé číslo (integer) jako výsledek.
### Je zaokrouhleno dolů na nejbližší celé číslo. V Pythonu, pokud se provádí celočíselné dělení mezi celým číslem a desetinným číslem, výsledek bude typu float.

